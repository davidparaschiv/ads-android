-- Rename technical logger action names to short, user-facing actions.
-- PostgreSQL enum value renames also update every existing logger_engine row
-- without deleting or recreating historical logs. Safe to run more than once.

begin;

do $migration$
declare
  v_old text;
  v_new text;
begin
  for v_old,v_new in
    select * from (values
      ('BV_RESOLVE_CURRENT_ACCOUNT_TYPE_AFTER_GOOGLE_AUTHENTICATION','BV_SIGN_IN'),
      ('CV_RESOLVE_CURRENT_ACCOUNT_TYPE_AFTER_GOOGLE_AUTHENTICATION','CV_SIGN_IN'),
