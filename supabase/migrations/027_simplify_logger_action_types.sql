    if exists(
      select 1
      from pg_type t
      join pg_namespace n on n.oid=t.typnamespace
      join pg_enum e on e.enumtypid=t.oid
      where n.nspname='public'
        and t.typname='logger_action_type'
        and e.enumlabel=v_old
    ) and not exists(
      select 1
      from pg_type t
      join pg_namespace n on n.oid=t.typnamespace
      join pg_enum e on e.enumtypid=t.oid
      where n.nspname='public'
        and t.typname='logger_action_type'
        and e.enumlabel=v_new
    ) then
      execute format(
        'alter type public.logger_action_type rename value %L to %L',
        v_old,
        v_new
      );
    end if;
  end loop;
end
